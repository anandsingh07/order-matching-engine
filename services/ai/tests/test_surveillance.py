"""Tests for the surveillance training pipeline, on a small committed sample
generated by the TypeScript simulator (pnpm --filter @ome/surveillance dataset)."""

import json
import pathlib

import numpy as np
import onnxruntime as ort
import pandas as pd
import pytest

from surveillance.train import LABELS, load, matrix, train

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "surveillance-small.csv"


@pytest.fixture(scope="module")
def trained(tmp_path_factory: pytest.TempPathFactory) -> tuple[dict, pathlib.Path]:
    out = tmp_path_factory.mktemp("models")
    return train(FIXTURE, out), out


def test_splits_by_whole_markets_so_nothing_leaks_between_train_validation_and_test() -> None:
    d = load(FIXTURE)
    train_seeds, validation_seeds, test_seeds = (set(f["seed"]) for f in (d.train, d.validation, d.test))
    assert train_seeds and validation_seeds and test_seeds
    assert not train_seeds & validation_seeds
    assert not train_seeds & test_seeds
    assert not validation_seeds & test_seeds
    # The unseen manipulation type never reaches the classifier.
    assert set(d.train["label"]) <= set(LABELS)
    assert set(d.novel["label"]) == {"quote_stuffing"}
    assert set(d.novel["seed"]) <= test_seeds


def test_writes_models_and_a_manifest_that_matches_the_data(trained: tuple[dict, pathlib.Path]) -> None:
    manifest, out = trained
    columns = pd.read_csv(FIXTURE, nrows=1).columns.tolist()
    assert manifest["features"] == [c for c in columns if c not in ("seed", "time", "trader", "label", "intensity")]
    assert manifest["labels"] == LABELS
    assert (out / "classifier.onnx").exists() and (out / "anomaly.onnx").exists()
    assert json.loads((out / "model.json").read_text()) == manifest
    assert set(manifest["baseline"]) == set(manifest["features"])


def test_onnx_files_reproduce_the_trained_models(trained: tuple[dict, pathlib.Path]) -> None:
    manifest, out = trained
    assert manifest["onnx_parity"]["classifier_same_prediction"] >= 0.995
    assert manifest["onnx_parity"]["classifier_max_abs_diff"] < 0.05
    assert manifest["onnx_parity"]["anomaly_max_rel_diff"] < 1e-3
    # And the files load and run on their own, as TypeScript will use them.
    x = matrix(load(FIXTURE).test, manifest["features"])[:5]
    probabilities = ort.InferenceSession(str(out / "classifier.onnx")).run(["probabilities"], {"features": x})[0]
    assert probabilities.shape == (5, len(LABELS))
    assert np.allclose(probabilities.sum(axis=1), 1, atol=1e-4)
    scores = ort.InferenceSession(str(out / "anomaly.onnx")).run(["score_samples"], {"features": x})[0]
    assert scores.shape[0] == 5


def test_detects_manipulation_in_markets_it_never_saw(trained: tuple[dict, pathlib.Path]) -> None:
    # Loose bounds: the fixture is small. The full dataset's numbers are in model.json.
    m = trained[0]["metrics"]
    assert m["manipulation_detected"] > 0.7
    assert m["honest_false_positive_rate"] < 0.1
    # The unseen type is evaluated, but its detection rate is not asserted here:
    # a 16-component density model fitted on a few small markets is too weak to
    # judge. The shipped model's rate (trained on 100 markets) is asserted on
    # fresh markets in packages/surveillance/test/model.test.ts.
    assert m["unseen_manipulation"]["labels"] == ["quote_stuffing"]
    assert m["unseen_manipulation"]["windows"] > 0
